-- =====================================================================
-- Migration: Dynamic Email + SMS Notifications
-- Adds:
--   1. smssettings table (generic SMS provider config)
--   2. services.notificationconfig column (per-service notification rules)
--   3. Backfill of existing global email templates into per-service rules
-- No data is destroyed. Safe to run multiple times.
-- =====================================================================

-- 1. SMS provider settings (single row, like emailsettings)
CREATE TABLE IF NOT EXISTS smssettings
(
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    providername      text,
    apiurl            text,
    httpmethod        text DEFAULT 'POST',
    apikey            text,
    keylocation       text DEFAULT 'header',
    keyname           text,
    senderid          text,
    bodytemplate      text,
    successindicator  text,
    enabled           boolean DEFAULT false
);

-- Seed a disabled row so the settings form has something to edit.
INSERT INTO smssettings (providername, enabled)
SELECT 'SMS Provider', false
WHERE NOT EXISTS (SELECT 1 FROM smssettings);

-- 2. Per-service notification rules
ALTER TABLE services ADD COLUMN IF NOT EXISTS notificationconfig jsonb;

-- 3. Backfill: copy the legacy global templates (emailsettings.templates keyed by
--    "Submission" / "OfficerAction") into each service's new per-action rules so
--    existing behaviour (email to the citizen on submit / officer action) persists
--    until the Designer re-configures each service. Services with no template get
--    channel "None" (no notification), matching the previous no-template behaviour.
UPDATE services s
SET notificationconfig = sub.config
FROM (
    SELECT
        e.templates->>'Submission'      AS sub_tpl,
        e.templates->>'OfficerAction'   AS off_tpl
    FROM emailsettings e
    LIMIT 1
) src,
LATERAL (
    SELECT jsonb_build_object(
        'Submission', jsonb_build_object(
            'channel',        CASE WHEN coalesce(src.sub_tpl,'') <> '' THEN 'Email' ELSE 'None' END,
            'emailSubject',   'Form Submission',
            'emailTemplate',  coalesce(src.sub_tpl,''),
            'smsTemplate',    '',
            'recipients',     jsonb_build_array(jsonb_build_object('type','Citizen'))
        ),
        'OfficerAction', jsonb_build_object(
            'channel',        CASE WHEN coalesce(src.off_tpl,'') <> '' THEN 'Email' ELSE 'None' END,
            'emailSubject',   'Application Status Update',
            'emailTemplate',  coalesce(src.off_tpl,''),
            'smsTemplate',    '',
            'recipients',     jsonb_build_array(jsonb_build_object('type','Citizen'))
        )
    )
) AS sub(config)
WHERE s.notificationconfig IS NULL
  AND EXISTS (SELECT 1 FROM emailsettings e);

